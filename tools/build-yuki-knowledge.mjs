// Yuki (the AI trip assistant, supabase/functions/yuki) answers from the
// same bundled content the app shows: the Arrivals guides and checklist
// (src/lib/arrivals.ts), the trip's legs (src/lib/places.ts) and emergency
// numbers and phrasebook (src/lib/phrases.ts) and the weather cities
// (src/lib/weather.ts). Edge Functions can't import the app's React
// Native modules, so this script bundles those files with esbuild (colours and
// photos stubbed out), runs them and writes the data as
// supabase/functions/yuki/knowledge.ts.
//
//   node tools/build-yuki-knowledge.mjs          # regenerate knowledge.ts
//   node tools/build-yuki-knowledge.mjs --check  # CI: fail if it's stale
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'supabase/functions/yuki/knowledge.ts');

const result = await build({
  stdin: {
    contents: `
      export { COUNTRIES, CHECKLIST, CHECKED, PASSPORT, airportByCode } from './src/lib/arrivals';
      export { STOPS } from './src/lib/places';
      export { EMERGENCY, LANGUAGES, PHRASES } from './src/lib/phrases';
      export { CITIES } from './src/lib/weather';
    `,
    resolveDir: root,
    loader: 'ts',
  },
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  write: false,
  logLevel: 'silent',
  loader: { '.jpg': 'empty', '.png': 'empty' },
  plugins: [
    {
      name: 'stubs',
      setup(b) {
        b.onResolve({ filter: /theme\/colors$/ }, () => ({ path: 'colors', namespace: 'stub' }));
        b.onResolve({ filter: /^react-native$|async-storage/ }, () => ({ path: 'rn', namespace: 'stub' }));
        b.onLoad({ filter: /.*/, namespace: 'stub' }, () => ({
          contents: 'const any = new Proxy({}, { get: () => "" }); export const legColors = any, legTextColors = any, colors = any; export default any;',
          loader: 'js',
        }));
      },
    },
  ],
});
const mod = await import(`data:text/javascript;base64,${Buffer.from(result.outputFiles[0].text).toString('base64')}`);

const codes = [...new Set(mod.COUNTRIES.flatMap((c) => c.airports))];
const knowledge = {
  checked: mod.CHECKED,
  passport: mod.PASSPORT,
  legs: mod.STOPS.map(({ key, city, country, dates, from }) => ({ key, city, country, dates, from })),
  countries: mod.COUNTRIES.map(({ key, name, dates, entry, visa, forms, tips, links, airports }) => ({
    key,
    name,
    dates,
    entry,
    visa,
    forms,
    tips,
    links,
    airports,
  })),
  airports: codes.map((c) => {
    const { map, ...a } = mod.airportByCode(c);
    return { ...a, mapLink: map.url };
  }),
  checklist: mod.CHECKLIST.map((c) => c.text),
  weatherCities: mod.CITIES.map(({ key, name, lat, lng, june }) => ({ key, name, lat, lng, typicalJune: june })),
  phrasebook: Object.fromEntries(
    Object.entries(mod.PHRASES).map(([cat, list]) => [
      cat,
      list.map((ph) => ({
        en: ph.en,
        japanese: `${ph.ja.text} (${ph.ja.say})`,
        mandarin: `${ph.zh.text} (${ph.zh.say})`,
        cantonese: `${ph.yue.text} (${ph.yue.say})`,
      })),
    ]),
  ),
  emergency: Object.fromEntries(
    Object.entries(mod.EMERGENCY).map(([k, v]) => {
      const lang = mod.LANGUAGES.find((l) => l.key === k);
      return [lang ? `${lang.where} (${lang.name})` : k, v];
    }),
  ),
};

const text =
  '// Generated by tools/build-yuki-knowledge.mjs from the app\'s bundled content — do not edit.\n' +
  '// Run `npm run build:yuki` after changing src/lib/arrivals.ts, places.ts or phrases.ts.\n' +
  `export const KNOWLEDGE = ${JSON.stringify(knowledge, null, 2)} as const;\n`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(out, 'utf8');
  } catch {
    // missing
  }
  if (current !== text) {
    console.error('yuki: knowledge.ts is stale — run `npm run build:yuki`');
    process.exit(1);
  }
  console.log('yuki: knowledge.ts is up to date');
} else {
  writeFileSync(out, text);
  console.log(`yuki: wrote ${out} (${text.length} bytes)`);
}
